import pytest

from papyrus_content.markus_renderer.content_markup import canonical_image_credit, canonicalize_image_credits


@pytest.mark.parametrize("written", [
    "Illustration generated with AI", "Illustration drafted by AI.", "Drafted by AI.", "AI-generated", "AI generated", "Generated",
    "generated.", "Image created by an AI", "Cover produced by artificial intelligence", "Photo made with a model", "Art rendered by machine",
])
def test_a_credit_that_only_says_a_machine_made_it_is_generated(written):
    assert canonical_image_credit(written) == "Generated"


@pytest.mark.parametrize("written", [
    "Image: U.S. Air Force / Trevor Cokley, Public domain via Wikimedia Commons", "Drafted by Ana Example", "Generated by Acme Studio", "", None,
])
def test_any_other_credit_is_unchanged(written):
    assert canonical_image_credit(written) == written


def test_only_image_directive_credits_in_a_source_are_rewritten():
    source = '::image{src="a.png" credit="Drafted by AI."}\n\nText credit="Drafted by AI."\n::image{src="b.png" credit=\'Real Person\'}\n'
    assert canonicalize_image_credits(source) == '::image{src="a.png" credit="Generated"}\n\nText credit="Drafted by AI."\n::image{src="b.png" credit=\'Real Person\'}\n'
