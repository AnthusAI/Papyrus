"""Generated story ideas as Items (features_backend/idea-items.feature). The backend is the in-memory fake."""

from __future__ import annotations

import json
import sys
from pathlib import Path

from behave import given, then, when

REPO_ROOT = Path(__file__).resolve().parents[2]
for entry in (REPO_ROOT / "src", REPO_ROOT):
    if str(entry) not in sys.path:
        sys.path.insert(0, str(entry))

from papyrus_content.ideas import monitor_stories  # noqa: E402
from papyrus_content.ideas.items import IdeaRefused, ItemStore, file_idea_item, generated_of, review_order  # noqa: E402
from papyrus_content.ideas.migrate import migrate, plan  # noqa: E402
from papyrus_content.story_from_reference import StoryCopiedFromReference  # noqa: E402
from papyrus_content.story_reporting import move_story_stage, story_references  # noqa: E402
from procedures.newsroom.tests import test_idea_items as support  # noqa: E402
from procedures.newsroom.tests.test_story_from_reference import NOW, SOURCE_TEXT, backend, reader  # noqa: E402


def state(context):
    if not hasattr(context, "ii"):
        context.ii = type("State", (), {"client": None, "result": None, "error": None, "plan": None, "proposals": [], "lineage": None})()
    return context.ii


def items(context):
    return state(context).client.list_records("Item")


@given('a Reference "{title}" with captured text')
def step_reference(context, title):
    state(context).client = backend()


def file(context, body=None, **changes):
    held = state(context)
    if body:
        changes["body"] = body
    try:
        held.result = file_idea_item(held.client, support.draft(**changes), now=NOW, source_text_reader=reader, gate=getattr(held, "gate", None))
        held.lineage = held.result["lineageId"]
    except (StoryCopiedFromReference, IdeaRefused) as error:
        held.error = error


@given("the pipeline filed an idea citing the Reference")
@when("the pipeline files an idea citing the Reference")
def step_file(context):
    file(context)
    state(context).first_lineage = state(context).lineage


@when("the pipeline files an idea whose body repeats the Reference's captured text")
def step_copy(context):
    file(context, body="Our view. " + SOURCE_TEXT + "\n")


@then("the Item is at the idea stage and is a draft")
def step_stage(context):
    [item] = items(context)
    assert item["stage"] == "idea" and item["status"] == "draft", item


@then('the Item records that it was generated by AI from the "{monitor}" monitor')
def step_generated(context, monitor):
    generated = generated_of(items(context)[0])
    assert generated["proposedBy"] == "AI" and generated["monitorId"] == monitor and generated["origin"] == "monitor", generated


@then('the Item is linked to the Reference as "{role}"')
def step_linked(context, role):
    held = state(context)
    assert [link["role"] for link in story_references(held.client, held.lineage)] == [role]


@then("the Item's body has no drafting bookkeeping line")
def step_body(context):
    assert "Section:" not in items(context)[0]["bodyMarkus"]


@then("exactly {count:d} Item exists")
def step_count(context, count):
    assert len(items(context)) == count


@then("exactly 1 Item exists at the idea stage")
def step_one_idea(context):
    [item] = items(context)
    assert item["stage"] == "idea"


@then("no Item exists")
def step_none(context):
    assert items(context) == []


@then("the filing is refused because the body is copied from the Reference")
def step_refused(context):
    assert isinstance(state(context).error, StoryCopiedFromReference)


@when('an editor moves the idea to spiked saying "{reason}"')
def step_spike(context, reason):
    held = state(context)
    move_story_stage(held.client, held.lineage, "spiked", actor="editor", reason=reason, now=NOW)


@then("the idea pipeline treats the Reference as already drafted")
def step_drafted(context):
    held = state(context)
    rows = ItemStore(held.client).story_drafts()
    assert rows[0]["state"] == "declined" and monitor_stories.drafted_lineage_ids(rows, []) == {"reference-clef"}


@given("these story draft Proposals:")
def step_proposals(context):
    held = state(context)
    held.proposals = [support.proposal(row["id"], state=row["state"], created=row["filed"] + "T00:00:00Z") for row in context.table]


@when("the editor runs the migration without writing")
def step_dry(context):
    held = state(context)
    held.plan = migrate(held.client, held.proposals, write=False)


@when("the editor runs the migration with writing")
def step_write(context):
    held = state(context)
    migrate(held.client, held.proposals, write=True, source_text_reader=reader, now=NOW)


@then('the plan converts "{first}", skips "{second}" as a duplicate and skips "{third}" as decided')
def step_plan(context, first, second, third):
    got = {entry["proposalId"]: (entry["action"], entry.get("reason")) for entry in state(context).plan["entries"]}
    assert got == {first: ("convert", None), second: ("skip", "duplicate"), third: ("skip", "decided")}, got


@then('running the plan again skips "{identifier}" because it is already covered')
def step_again(context, identifier):
    held = state(context)
    got = {entry["proposalId"]: entry.get("reason") for entry in plan(held.client, held.proposals)}
    assert got[identifier] == "already_covered", got


@given('the site\'s editorial check finds an error violation of "{policy}" and a warning')
def step_gate_error(context, policy):
    state(context).gate = support.FakeGate([support.finding("error", policy=policy), support.finding("warn")])


@given("the site's editorial check finds only a warning")
def step_gate_warn(context):
    state(context).gate = support.FakeGate([support.finding("warn")])


@given("the judgment lane is unavailable because no TYPESAFE_API_KEY is set")
def step_gate_unavailable(context):
    state(context).gate = support.FakeGate(classifier={"status": "unavailable", "reason": "no decision model is configured (set TYPESAFE_API_KEY)"})


@then('the filing is refused and the reason names "{policy}"')
def step_refused_policy(context, policy):
    error = state(context).error
    assert isinstance(error, IdeaRefused) and policy in str(error)


@then("the Item keeps {count:d} warning in its check result")
def step_warning_kept(context, count):
    assert generated_of(items(context)[0])["check"]["counts"]["warn"] == count


@then("the check is stored as the Item's check run")
def step_check_run(context):
    assert [item_id for item_id, _ in state(context).gate.recorded] == [items(context)[0]["id"]]


@then("the Item's check says the judgment lane did not run and why")
def step_judgment(context):
    judgment = generated_of(items(context)[0])["check"]["judgment"]
    assert judgment["ran"] is False and "TYPESAFE_API_KEY" in judgment["reason"]


@given("three ideas with no findings, one warning and one note")
def step_three(context):
    state(context).ideas = [{"ideaId": "warning", "editorialCheck": {"counts": {"error": 0, "warn": 1, "info": 0}}}, {"ideaId": "clean"}, {"ideaId": "note", "editorialCheck": {"counts": {"error": 0, "warn": 0, "info": 1}}}]


@then("the review lists them in that order: no findings, then the note, then the warning")
def step_order(context):
    assert [idea["ideaId"] for idea in review_order(state(context).ideas)] == ["clean", "note", "warning"]


@when("a roundup idea that supersedes it is filed")
def step_roundup(context):
    held = state(context)
    file(context, ideaId="idea-roundup", supersedes=[held.lineage], title="Clef roundup", targets=[{"type": "entity", "id": "topic-clef"}])


@then("the roundup records the earlier idea's lineage as superseded")
def step_superseded(context):
    held = state(context)
    roundup = next(item for item in items(context) if item["lineageId"] == held.result["lineageId"])
    assert generated_of(roundup)["supersedes"] == [state(context).first_lineage]


@given('three generated ideas: one the editor moved forward, one the editor spiked saying "{reason}", and one still waiting')
def step_decided(context, reason):
    held = state(context)
    held.client, held.accepted, held.declined, _pending = support.decided_world()


@then("the pipeline's feedback holds an accept and a decline with the reason, and nothing for the waiting idea")
def step_feedback(context):
    from papyrus_content.ideas.labels import feedback_entries

    entries = feedback_entries(state(context).client)
    assert [entry["verdict"] for entry in entries] == ["accept", "decline"] and "Too basic" in entries[1]["note"], entries


@then("the Cyclotron export has an include row and an exclude row that carry the reason and the cited Reference")
def step_export(context):
    from papyrus_content.ideas.labels import export_rows

    rows = export_rows(state(context).client)
    labels = [row["labels"]["idea-accept"] for row in rows]
    assert [label["label"] for label in labels] == ["include", "exclude"] and "Too basic" in labels[1]["explanation"]
    assert rows[0]["provenance"]["referenceLineageIds"] == ["reference-clef"]


@then("no Message was written")
def step_no_messages(context):
    assert not state(context).client.tables.get("Message")


@given("three ideas filed in one morning run")
def step_morning(context):
    held = state(context)
    held.client = support.backend()
    held.run = {"runId": "monitor-stories-run-20261101T070000Z-abc123"}
    held.morning = [
        file_idea_item(held.client, support.draft(ideaId=f"idea-{n}", title=f"Morning idea {n}", targets=[{"type": "entity", "id": f"topic-{n}"}]), now=NOW)
        for n in (1, 2, 3)
    ]
    held.run_ideas = [{"ideaId": f"idea-{n}", "itemLineageId": result["lineageId"]} for n, result in enumerate(held.morning, 1)]


@when("the run raises its review request")
def step_raise(context):
    from papyrus_content.ideas.review import request_human_review

    held = state(context)
    held.review = request_human_review(held.client, held.run, held.run_ideas)


@then("all three ideas are in the Idea column of the Stories board")
def step_column(context):
    assert [item["stage"] for item in items(context)] == ["idea", "idea", "idea"]


@then("exactly one review request is open for the run, and its links are those three ideas as stories")
def step_request(context):
    held = state(context)
    requests = [row for row in held.client.list_records("ReviewRequest") if row["state"] == "open"]
    assert len(requests) == 1 and held.review["linkedAs"] == "story", held.review
    links = json.loads(requests[0]["links"])
    assert [(link["type"], link["id"]) for link in links] == [("story", result["lineageId"]) for result in held.morning]
    assert json.loads(requests[0]["subject"]) == {"type": "batch", "id": held.run["runId"]}


@then("no Proposal is filed for any of them")
def step_no_proposal(context):
    assert not state(context).client.tables.get("Proposal")


@then("the review request tells the editor to move an idea forward to accept it or to Spiked with a reason to decline it")
def step_ask(context):
    [request] = state(context).client.list_records("ReviewRequest")
    assert "forward to accept it" in request["ask"] and "Spiked with a reason to decline it" in request["ask"], request["ask"]


@when('an editor moves the first idea forward to "{stage}" and spikes the second saying "{reason}"')
def step_decide(context, stage, reason):
    held = state(context)
    move_story_stage(held.client, held.morning[0]["lineageId"], stage, actor="editor", reason="good angle", now="2026-11-01T10:00:00Z")
    move_story_stage(held.client, held.morning[1]["lineageId"], "spiked", actor="editor", reason=reason, now="2026-11-01T10:30:00Z")


@then("the first and second ideas have left the Idea column and the third is still in it")
def step_left(context):
    held = state(context)
    stages = {row["lineageId"]: row["stage"] for row in held.client.list_records("Item")}
    assert [stages[result["lineageId"]] for result in held.morning] == ["reporting", "spiked", "idea"], stages


@then("the pipeline's feedback holds an accept for the first idea and a decline with the reason for the second")
def step_morning_feedback(context):
    from papyrus_content.ideas.labels import feedback_entries

    entries = feedback_entries(state(context).client)
    assert [(entry["title"], entry["verdict"]) for entry in entries] == [("Morning idea 1", "accept"), ("Morning idea 2", "decline")], entries
    assert "Too basic" in entries[1]["note"]


@then("the third idea has no decision yet")
def step_third(context):
    from papyrus_content.ideas.labels import feedback_entries

    assert "Morning idea 3" not in [entry["title"] for entry in feedback_entries(state(context).client)]
