"""Generated story ideas as Items (features_backend/idea-items.feature). The backend is the in-memory fake."""

from __future__ import annotations

import sys
from pathlib import Path

from behave import given, then, when

REPO_ROOT = Path(__file__).resolve().parents[2]
for entry in (REPO_ROOT / "src", REPO_ROOT):
    if str(entry) not in sys.path:
        sys.path.insert(0, str(entry))

from papyrus_content.ideas import monitor_stories  # noqa: E402
from papyrus_content.ideas.items import ItemStore, file_idea_item, generated_of  # noqa: E402
from papyrus_content.ideas.migrate import migrate, plan  # noqa: E402
from papyrus_content.story_from_reference import StoryCopiedFromReference  # noqa: E402
from papyrus_content.story_reporting import move_story_stage, story_references  # noqa: E402
from procedures.newsroom.tests import test_idea_items as support  # noqa: E402
from procedures.newsroom.tests.test_story_from_reference import NOW, SOURCE_TEXT, backend, reader  # noqa: E402


def state(context):
    if not hasattr(context, "ii"):
        context.ii = type("State", (), {"client": None, "result": None, "error": None, "plan": None, "proposals": [], "lineage": None})()
    return context.ii


def items(context):
    return state(context).client.list_records("Item")


@given('a Reference "{title}" with captured text')
def step_reference(context, title):
    state(context).client = backend()


def file(context, body=None):
    held = state(context)
    changes = {"body": body} if body else {}
    try:
        held.result = file_idea_item(held.client, support.draft(**changes), now=NOW, source_text_reader=reader)
        held.lineage = held.result["lineageId"]
    except StoryCopiedFromReference as error:
        held.error = error


@given("the pipeline filed an idea citing the Reference")
@when("the pipeline files an idea citing the Reference")
def step_file(context):
    file(context)


@when("the pipeline files an idea whose body repeats the Reference's captured text")
def step_copy(context):
    file(context, body="Our view. " + SOURCE_TEXT + "\n")


@then("the Item is at the idea stage and is a draft")
def step_stage(context):
    [item] = items(context)
    assert item["stage"] == "idea" and item["status"] == "draft", item


@then('the Item records that it was generated by AI from the "{monitor}" monitor')
def step_generated(context, monitor):
    generated = generated_of(items(context)[0])
    assert generated["proposedBy"] == "AI" and generated["monitorId"] == monitor and generated["origin"] == "monitor", generated


@then('the Item is linked to the Reference as "{role}"')
def step_linked(context, role):
    held = state(context)
    assert [link["role"] for link in story_references(held.client, held.lineage)] == [role]


@then("the Item's body has no drafting bookkeeping line")
def step_body(context):
    assert "Section:" not in items(context)[0]["bodyMarkus"]


@then("exactly {count:d} Item exists")
def step_count(context, count):
    assert len(items(context)) == count


@then("exactly 1 Item exists at the idea stage")
def step_one_idea(context):
    [item] = items(context)
    assert item["stage"] == "idea"


@then("no Item exists")
def step_none(context):
    assert items(context) == []


@then("the filing is refused because the body is copied from the Reference")
def step_refused(context):
    assert isinstance(state(context).error, StoryCopiedFromReference)


@when('an editor moves the idea to spiked saying "{reason}"')
def step_spike(context, reason):
    held = state(context)
    move_story_stage(held.client, held.lineage, "spiked", actor="editor", reason=reason, now=NOW)


@then("the idea pipeline treats the Reference as already drafted")
def step_drafted(context):
    held = state(context)
    rows = ItemStore(held.client).story_drafts()
    assert rows[0]["state"] == "declined" and monitor_stories.drafted_lineage_ids(rows, []) == {"reference-clef"}


@given("these story draft Proposals:")
def step_proposals(context):
    held = state(context)
    held.proposals = [support.proposal(row["id"], state=row["state"], created=row["filed"] + "T00:00:00Z") for row in context.table]


@when("the editor runs the migration without writing")
def step_dry(context):
    held = state(context)
    held.plan = migrate(held.client, held.proposals, write=False)


@when("the editor runs the migration with writing")
def step_write(context):
    held = state(context)
    migrate(held.client, held.proposals, write=True, source_text_reader=reader, now=NOW)


@then('the plan converts "{first}", skips "{second}" as a duplicate and skips "{third}" as decided')
def step_plan(context, first, second, third):
    got = {entry["proposalId"]: (entry["action"], entry.get("reason")) for entry in state(context).plan["entries"]}
    assert got == {first: ("convert", None), second: ("skip", "duplicate"), third: ("skip", "decided")}, got


@then('running the plan again skips "{identifier}" because it is already covered')
def step_again(context, identifier):
    held = state(context)
    got = {entry["proposalId"]: entry.get("reason") for entry in plan(held.client, held.proposals)}
    assert got[identifier] == "already_covered", got
