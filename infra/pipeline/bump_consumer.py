#!/usr/bin/env python3
"""Open a `chore: bump Papyrus to X` pull request on a Papyrus site repository.

Run by the reusable workflow `.github/workflows/bump-consumer.yml` from a checkout of the site's integration branch. It finds the newest
Papyrus version published on both PyPI (`papyrus-newsroom`) and npm (`@anthusai/papyrus`), rewrites every line that pins the current version,
refreshes both lockfiles, and opens the pull request with the release notes between the two versions. A deploy can add only one
DynamoDB global secondary index per table, so when the jump would change more than one index on any existing table the pull request is
opened as a draft whose body says which tables need the bump staged.

Usage:  python3 infra/pipeline/bump_consumer.py --site SITE_DIR --papyrus PAPYRUS_CHECKOUT --base BRANCH [--ci-workflow FILE] [--dry-run]
The Papyrus checkout needs the release tags (`v5.105.0`) and its `amplify/` tree. Environment: GH_TOKEN for `gh`, unless --dry-run.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

PYPI_URL = "https://pypi.org/pypi/papyrus-newsroom/json"
NPM_URL = "https://registry.npmjs.org/@anthusai%2fpapyrus"
BRANCH_PREFIX = "chore/bump-papyrus-"
RELEASE = re.compile(r"^\d+\.\d+\.\d+$")
RELEASING_TYPES = re.compile(r"^(feat|fix|perf)(\([^)]*\))?!?:|^[a-z]+(\([^)]*\))?!:")
PR_BODY_LIMIT = 60000  # GitHub rejects bodies over 65536 characters
# Not pins: lockfiles are regenerated by npm, the board is the site's own record.
UNPINNED = re.compile(r"(^|/)(package-lock\.json|project/)")


def run(args: list[str], cwd: Path, check: bool = True) -> str:
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"{' '.join(args)} failed in {cwd}: {result.stderr.strip() or result.stdout.strip()}")
    return result.stdout


def fetch_json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=60) as response:
        return json.load(response)


def key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def newest_common(pypi_url: str, npm_url: str) -> str:
    pypi = {v for v, files in fetch_json(pypi_url)["releases"].items() if RELEASE.match(v) and any(not f.get("yanked") for f in files)}
    npm = {v for v in fetch_json(npm_url)["versions"] if RELEASE.match(v)}
    both = pypi & npm
    if not both:
        sys.exit("no release is published on both PyPI and npm")
    return max(both, key=key)


def current_pin(site: Path) -> str:
    version = json.loads((site / "infra" / "site.json").read_text())["papyrusVersion"]
    if not RELEASE.match(version):
        sys.exit(f"infra/site.json pins {version}, which is not a released version; bump by hand first")
    return version


def pin_files(site: Path, old: str) -> list[Path]:
    """Tracked files with a line that names Papyrus and the current pin. Other versions on such lines (history, comments) are untouched."""
    tracked = run(["git", "ls-files", "-z"], site).split("\0")
    boundary = re.compile(rf"(?<![\d.]){re.escape(old)}(?![\d.]|\w)")
    found = []
    for name in filter(None, tracked):
        if UNPINNED.search(name):
            continue
        try:
            text = (site / name).read_text()
        except (UnicodeDecodeError, FileNotFoundError):
            continue
        if any("papyrus" in line.lower() and boundary.search(line) for line in text.splitlines()):
            found.append(site / name)
    return found


def rewrite(path: Path, old: str, new: str) -> None:
    boundary = re.compile(rf"(?<![\d.]){re.escape(old)}(?![\d.]|\w)")
    lines = path.read_text().splitlines(keepends=True)
    path.write_text("".join(boundary.sub(new, line) if "papyrus" in line.lower() else line for line in lines))


# --- DynamoDB index check -------------------------------------------------------------------------------------------------------

def balanced(text: str, start: int) -> int:
    """Index just past the parenthesis group that opens at text[start]."""
    depth = 0
    for i in range(start, len(text)):
        depth += {"(": 1, ")": -1}.get(text[i], 0)
        if depth == 0:
            return i + 1
    sys.exit("unbalanced parentheses in a schema file")


def indexes_in(text: str) -> dict[str, set[str]]:
    """Map model name to its secondary indexes, each as key field, sort keys and explicit name (the query field does not change the table)."""
    models: dict[str, set[str]] = {}
    headers = list(re.finditer(r"^[ \t]*([A-Z]\w*):[ \t]", text, re.M))
    for call in re.finditer(r"\.secondaryIndexes\(", text):
        owner = [h for h in headers if h.start() < call.start()]
        if not owner:
            sys.exit("a secondaryIndexes call with no model name above it")
        end = balanced(text, call.end() - 1)
        found = models.setdefault(owner[-1].group(1), set())
        body = text[call.end():end]
        for index in re.finditer(r'\bindex\(\s*"([^"]+)"\s*\)', body):
            position, parts = index.end(), {"sortKeys": "", "name": ""}
            while True:
                chained = re.compile(r"\s*\.(\w+)\(").match(body, position)
                if not chained:
                    break
                position = balanced(body, chained.end() - 1)
                if chained.group(1) in parts:
                    parts[chained.group(1)] = re.sub(r"\s+", "", body[chained.end():position - 1])
            found.add(f'{index.group(1)}|{parts["sortKeys"]}|{parts["name"]}')
    return models


def indexes_at(papyrus: Path, ref: str) -> dict[str, set[str]]:
    models: dict[str, set[str]] = {}
    for name in run(["git", "grep", "-l", "secondaryIndexes", ref, "--", "amplify"], papyrus, check=False).split():
        path = name.split(":", 1)[1]
        for model, found in indexes_in(run(["git", "show", f"{ref}:{path}"], papyrus)).items():
            models.setdefault(model, set()).update(found)
    return models


def staged_tables(papyrus: Path, old: str, new: str) -> dict[str, tuple[int, int]]:
    """Existing tables whose index set changes by more than one create or delete between the two releases: table -> (added, removed)."""
    before, after = indexes_at(papyrus, f"v{old}"), indexes_at(papyrus, f"v{new}")
    changes = {}
    for model in before.keys() | after.keys():
        if model not in before:
            continue  # a new table is created with all its indexes at once
        added, removed = len(after.get(model, set()) - before[model]), len(before[model] - after.get(model, set()))
        if added + removed > 1:
            changes[model] = (added, removed)
    return dict(sorted(changes.items()))


# --- Pull request ---------------------------------------------------------------------------------------------------------------

def release_notes(papyrus: Path, old: str, new: str) -> tuple[list[str], int]:
    subjects = run(["git", "log", "--no-merges", "--format=%s", f"v{old}..v{new}"], papyrus).splitlines()
    notes = [s for s in subjects if RELEASING_TYPES.match(s)]
    return notes, len(subjects) - len(notes)


def pr_body(old: str, new: str, notes: list[str], unlisted: int, staged: dict[str, tuple[int, int]]) -> str:
    lines = [f"Moves the Papyrus pin from {old} to {new}: `@anthusai/papyrus` and `papyrus-newsroom`, every line that names the old pin, and both lockfiles.", ""]
    if staged:
        lines += [
            "## Staged bump needed: this is a draft",
            "A deploy can add only one DynamoDB index per table, and these tables change by more than one between the two releases:",
            "",
            *[f"- `{model}`: {added} added, {removed} removed" for model, (added, removed) in staged.items()],
            "",
            f"Do not merge this as it stands. Bump to each release in between (`git tag` in AnthusAI/Papyrus lists them) and deploy after each, "
            f"so no deploy adds more than one index to a table.",
            "",
        ]
    else:
        lines += ["Index check: no existing table gains or loses more than one DynamoDB index between these releases, so one deploy can carry this bump.", ""]
    lines += [f"## Releasing changes in {old}..{new}", *([f"- {note}" for note in notes] or ["- none"]), ""]
    if unlisted:
        lines.append(f"{unlisted} further commits (chore, docs, tests, refactors) do not change released behaviour.")
    body = "\n".join(lines)
    if len(body) > PR_BODY_LIMIT:
        body = body[:PR_BODY_LIMIT].rsplit("\n", 1)[0] + f"\n\n(The list is cut at GitHub's size limit; see https://github.com/AnthusAI/Papyrus/compare/v{old}...v{new}.)"
    return body


def open_bump_branches(site: Path) -> dict[str, int]:
    listing = json.loads(run(["gh", "pr", "list", "--state", "open", "--json", "number,headRefName", "--limit", "100"], site))
    return {pr["headRefName"]: pr["number"] for pr in listing if pr["headRefName"].startswith(BRANCH_PREFIX)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--site", type=Path, default=Path("."))
    parser.add_argument("--papyrus", type=Path, required=True)
    parser.add_argument("--base", required=True, help="the integration branch the pull request targets (already checked out in --site)")
    parser.add_argument("--ci-workflow", default="", help="workflow file to dispatch on the new branch, because pull requests opened with GITHUB_TOKEN start no checks")
    parser.add_argument("--dry-run", action="store_true", help="report what would happen and change nothing")
    parser.add_argument("--pypi-url", default=PYPI_URL)
    parser.add_argument("--npm-url", default=NPM_URL)
    args = parser.parse_args()
    site, papyrus = args.site.resolve(), args.papyrus.resolve()

    old, new = current_pin(site), newest_common(args.pypi_url, args.npm_url)
    if key(new) <= key(old):
        print(f"Papyrus {old} is current (newest on both registries: {new}); nothing to open.")
        return
    branch = f"{BRANCH_PREFIX}{new}"
    existing = {} if args.dry_run else open_bump_branches(site)
    if branch in existing:
        print(f"Pull request #{existing[branch]} already bumps to {new}.")
        return

    files = pin_files(site, old)
    staged = staged_tables(papyrus, old, new)
    notes, unlisted = release_notes(papyrus, old, new)
    print(f"Bump {old} -> {new}: {len(files)} pinned files ({', '.join(str(f.relative_to(site)) for f in files)}); "
          f"{'DRAFT, staged bump needed for ' + ', '.join(staged) if staged else 'one-deploy bump'}; {len(notes)} releasing changes.")
    if args.dry_run:
        return

    run(["git", "checkout", "-b", branch], site)
    for path in files:
        rewrite(path, old, new)
    for directory in (site, site / "infra"):
        if (directory / "package-lock.json").exists():
            run(["npm", "install", "--package-lock-only", "--ignore-scripts"], directory)
    title = f"chore: bump Papyrus to {new}"
    run(["git", "-c", "user.name=github-actions[bot]", "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com", "commit", "-a", "-m", title], site)
    run(["git", "push", "origin", branch], site)
    draft = ["--draft"] if staged else []
    run(["gh", "pr", "create", "--base", args.base, "--head", branch, "--title", title, "--body", pr_body(old, new, notes, unlisted, staged), *draft], site)
    if args.ci_workflow:
        run(["gh", "workflow", "run", args.ci_workflow, "--ref", branch], site)
    for superseded, number in open_bump_branches(site).items():
        if superseded != branch:
            run(["gh", "pr", "close", str(number), "--delete-branch", "--comment", f"Superseded by the bump to {new}."], site)


if __name__ == "__main__":
    main()
