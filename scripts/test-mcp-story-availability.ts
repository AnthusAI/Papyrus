import assert from 'node:assert/strict';
import { App, Stack } from 'aws-cdk-lib';
import { Table, AttributeType } from 'aws-cdk-lib/aws-dynamodb';
import { Function as LambdaFunction, Runtime, Code } from 'aws-cdk-lib/aws-lambda';
import { Template, Match } from 'aws-cdk-lib/assertions';
import { addMcpTools } from '../amplify/mcp-tools/resource';
import { BOOTSTRAP_DEFERRED_GROUPS, baseModelNames } from '../amplify/data/schema';
import { storyPublicationRequestsAvailable, wireMcpStoryTables } from '../amplify/mcp-tools/story-availability';

const app = new App();
const stack = new Stack(app, 'test');
const item = new Table(stack, 'Item', { partitionKey: { name: 'id', type: AttributeType.STRING } });
const review = new Table(stack, 'Review', { partitionKey: { name: 'id', type: AttributeType.STRING } });
const settings = new Table(stack, 'Settings', { partitionKey: { name: 'id', type: AttributeType.STRING } });
const makeFn = (id: string) => new LambdaFunction(stack, id, { runtime: Runtime.PYTHON_3_12, handler: 'index.handler', code: Code.fromInline('def handler(e, c): pass') });
const bootstrap = baseModelNames([...BOOTSTRAP_DEFERRED_GROUPS]);
assert.ok(bootstrap.includes('Item') && !bootstrap.includes('ReviewRequest') && !bootstrap.includes('EditorialCheckSettings'));
assert.ok(bootstrap.includes('agentRequestStoryPublish'), 'custom action remains in the schema');
assert.equal(storyPublicationRequestsAvailable({ Item: item }), false);
assert.equal(storyPublicationRequestsAvailable({ Item: item, ReviewRequest: review }), false);
assert.equal(storyPublicationRequestsAvailable({ ReviewRequest: review, EditorialCheckSettings: settings }), false);
assert.equal(storyPublicationRequestsAvailable({ Item: item, ReviewRequest: review, EditorialCheckSettings: settings }), true);
assert.doesNotThrow(() => wireMcpStoryTables(makeFn('NoTables'), {}));
wireMcpStoryTables(makeFn('Bootstrap'), { Item: item });
wireMcpStoryTables(makeFn('Full'), { Item: item, ReviewRequest: review, EditorialCheckSettings: settings });
const template = Template.fromStack(stack);
template.hasResourceProperties('AWS::Lambda::Function', { Environment: { Variables: Match.objectLike({ PAPYRUS_MCP_STORY_PUBLISH_REQUEST_ENABLED: 'true', PAPYRUS_ITEM_TABLE: Match.anyValue(), PAPYRUS_REVIEW_REQUEST_TABLE: Match.anyValue() }) } });
const functions = Object.values(template.findResources('AWS::Lambda::Function')) as Array<{ Properties: { Environment?: { Variables?: Record<string, unknown> } } }>;
assert.equal(functions.filter(fn => fn.Properties.Environment?.Variables?.PAPYRUS_MCP_STORY_PUBLISH_REQUEST_ENABLED === 'true').length, 1);
const plan = { origin: 'https://cms.example', invokerRoleArn: 'arn:aws:iam::123456789012:role/site-compute' };
const bootstrapStack = new Stack(new App(), 'BootstrapTools');
addMcpTools(bootstrapStack, plan, { endpoint: 'https://example/graphql', tenant: '', publication: '', storyDrafts: true, storyPublishRequests: false }, Code.fromInline('def handler(event, context): pass'));
const bootstrapFunctions = Object.values(Template.fromStack(bootstrapStack).findResources('AWS::Lambda::Function')) as Array<{ Properties: { Environment: { Variables: Record<string, unknown> } } }>;
const vars = bootstrapFunctions.find(fn => fn.Properties.Environment.Variables.PAPYRUS_GRAPHQL_ENDPOINT)?.Properties.Environment.Variables;
assert.equal(vars?.PAPYRUS_MCP_STORY_DRAFT_ENABLED, 'true');
assert.equal(vars?.PAPYRUS_MCP_STORY_PUBLISH_REQUEST_ENABLED, undefined);
const fullStack = new Stack(new App(), 'FullTools');
addMcpTools(fullStack, plan, { endpoint: 'https://example/graphql', tenant: '', publication: '', storyDrafts: true, storyPublishRequests: true }, Code.fromInline('def handler(event, context): pass'));
Template.fromStack(fullStack).hasResourceProperties('AWS::Lambda::Function', { Environment: { Variables: Match.objectLike({ PAPYRUS_MCP_STORY_PUBLISH_REQUEST_ENABLED: 'true' }) } });
console.log('MCP Story model availability checks passed');
