import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sync, readReaderBasePath } from "../packages/papyrus/src/sync.mjs";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const quiet = () => {};

const manifest = {
  version: "0.0.0-test",
  routes: [
    { file: "app/layout.tsx", hasDefault: true, exports: ["metadata"], config: {} },
    { file: "app/page.tsx", reader: true, hasDefault: true, exports: [], config: { dynamic: '"force-dynamic"' } },
    { file: "app/[year]/[month]/[day]/page.tsx", reader: true, hasDefault: true, exports: ["generateMetadata"], config: {} },
    { file: "app/articles/[slug]/page.tsx", reader: true, hasDefault: true, exports: [], config: {} },
    { file: "app/archive/page.tsx", reader: true, hasDefault: true, exports: [], config: {} },
    { file: "app/settings/page.tsx", reader: true, hasDefault: true, exports: [], config: {} },
    { file: "app/robots.ts", hasDefault: true, exports: [], config: {} },
    { file: "app/newsroom/page.tsx", hasDefault: true, exports: [], config: {} },
    { file: "app/api/revalidate/route.ts", hasDefault: false, exports: ["POST"], config: {} },
    { file: "app/%5F_preview/[[...path]]/route.ts", hasDefault: false, exports: ["GET"], config: {} },
  ],
  middleware: { file: "middleware.ts", matcher: null },
};

function tempSite(config) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "papyrus-sync-"));
  if (config !== undefined) fs.writeFileSync(path.join(root, "papyrus.config.ts"), config);
  return root;
}

function filesUnder(root) {
  const found = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else found.push(path.relative(root, full).split(path.sep).join("/"));
    }
  };
  walk(root);
  return found.filter((f) => !f.startsWith(".papyrus/") && f !== ".gitignore" && f !== "papyrus.config.ts").sort();
}

const READER_FILES = [
  "app/page.tsx",
  "app/[year]/[month]/[day]/page.tsx",
  "app/articles/[slug]/page.tsx",
  "app/archive/page.tsx",
  "app/settings/page.tsx",
];
const ROOT_FILES = ["app/layout.tsx", "app/robots.ts", "app/newsroom/page.tsx", "app/api/revalidate/route.ts", "app/%5F_preview/[[...path]]/route.ts", "middleware.ts"];

const defaultRoot = tempSite("export default {};\n");
try {
  sync({ root: defaultRoot, log: quiet, manifest });
  assert.deepEqual(filesUnder(defaultRoot), [...READER_FILES, ...ROOT_FILES].sort(), "default sync writes every shim at its own path");
  assert.equal(
    fs.readFileSync(path.join(defaultRoot, "app/page.tsx"), "utf8"),
    '// GENERATED by `papyrus-app sync` from @anthusai/papyrus. Do not edit; add a site-owned file at this path to override.\nexport { default } from "@anthusai/papyrus/app/page";\nexport const dynamic = "force-dynamic";\n',
    "default root page shim is unchanged",
  );
  const logs = [];
  sync({ root: defaultRoot, log: (line) => logs.push(line), manifest });
  assert.equal(logs[0], "papyrus-app sync: 11 shim(s) written, 0 site-owned file(s) kept (@anthusai/papyrus@0.0.0-test)", "default log line is unchanged");
} finally {
  fs.rmSync(defaultRoot, { recursive: true, force: true });
}

const mountedRoot = tempSite('export default { brand: { readerBasePath: "/information" } };\n');
try {
  assert.equal(readReaderBasePath(mountedRoot), "/information", "base path is read from papyrus.config.ts");
  sync({ root: mountedRoot, log: quiet, manifest });
  const mountedReader = READER_FILES.map((f) => f.replace(/^app\//, "app/information/"));
  assert.deepEqual(filesUnder(mountedRoot), [...mountedReader, ...ROOT_FILES].sort(), "reader shims move under app/information, none at root");
  assert.ok(!fs.existsSync(path.join(mountedRoot, "app/page.tsx")), "no root page shim");
  assert.ok(!fs.existsSync(path.join(mountedRoot, "app/archive")), "no root archive");
  assert.ok(fs.readFileSync(path.join(mountedRoot, "app/information/page.tsx"), "utf8").includes('"@anthusai/papyrus/app/page"'), "home shim still points at the package page");
  const gitignore = fs.readFileSync(path.join(mountedRoot, ".gitignore"), "utf8");
  assert.ok(gitignore.includes("/app/information/archive/page.tsx") && !gitignore.includes("\n/app/archive/page.tsx"), "gitignore lists the mounted shims");

  const before = filesUnder(mountedRoot).map((f) => fs.readFileSync(path.join(mountedRoot, f), "utf8"));
  const gitignoreBefore = gitignore;
  sync({ root: mountedRoot, log: quiet, manifest });
  assert.deepEqual(filesUnder(mountedRoot).map((f) => fs.readFileSync(path.join(mountedRoot, f), "utf8")), before, "second sync is a no-op");
  assert.equal(fs.readFileSync(path.join(mountedRoot, ".gitignore"), "utf8"), gitignoreBefore, "second sync leaves .gitignore unchanged");

  fs.writeFileSync(path.join(mountedRoot, "app/page.tsx"), "export default function Marketing() { return null; }\n");
  const logs = [];
  sync({ root: mountedRoot, log: (line) => logs.push(line), manifest });
  assert.ok(fs.readFileSync(path.join(mountedRoot, "app/page.tsx"), "utf8").includes("Marketing"), "a site-owned root page is kept");
  assert.ok(!fs.existsSync(path.join(mountedRoot, "app/archive/page.tsx")), "still no root archive");

  sync({ root: mountedRoot, log: quiet, manifest, readerBasePath: "" });
  assert.ok(fs.existsSync(path.join(mountedRoot, "app/archive/page.tsx")), "removing the base path restores root shims");
  assert.ok(!fs.existsSync(path.join(mountedRoot, "app/information/archive/page.tsx")), "removing the base path removes the mounted shims");
  assert.ok(fs.readFileSync(path.join(mountedRoot, "app/page.tsx"), "utf8").includes("Marketing"), "the site-owned root page survives the toggle");
} finally {
  fs.rmSync(mountedRoot, { recursive: true, force: true });
}

assert.throws(() => sync({ root: tempSite(), log: quiet, manifest, readerBasePath: "/newsroom" }), /collides/, "newsroom base path is rejected");
assert.equal(readReaderBasePath(tempSite()), "", "missing config means no base path");

const outDir = fs.mkdtempSync(path.join(os.tmpdir(), "papyrus-sync-stage-"));
try {
  const stageOutput = execFileSync("node", [path.join(repo, "packages/papyrus/scripts/stage.mjs"), "--version", "0.0.0-sync.1", "--out", outDir], {
    cwd: repo,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  const report = JSON.parse(stageOutput.slice(stageOutput.indexOf("{")));
  const staged = JSON.parse(fs.readFileSync(path.join(outDir, "stage-papyrus/routes.manifest.json"), "utf8"));
  assert.ok(report.routes > 0);
  const readerFiles = staged.routes.filter((r) => r.reader).map((r) => r.file).sort();
  assert.deepEqual(
    readerFiles,
    [
      "app/[year]/[month]/[day]/[articleSlug]/page.tsx",
      "app/[year]/[month]/[day]/page.tsx",
      "app/[year]/[month]/[day]/page/[pageNumber]/page.tsx",
      "app/[year]/[month]/[day]/section/[sectionKey]/page.tsx",
      "app/archive/page.tsx",
      "app/articles/[slug]/page.tsx",
      "app/page.tsx",
      "app/settings/page.tsx",
    ],
    "the real manifest marks exactly the reader routes",
  );
} finally {
  fs.rmSync(outDir, { recursive: true, force: true });
}

console.log("test-sync-reader-base-path: ok");
